"""Generate the Rust contract types of the message SDK from the schemas.

  generate-rust.py           write contrib-addons/sdk/message-v1/src/contract.rs
  generate-rust.py --check   exit 1 when the file differs from the schemas

The enumerations and limits come from metadata-result.schema.json and
discovery-page.schema.json, so a schema change shows here as drift.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parent / "message-v1" / "src" / "contract.rs"


def load(name):
    return json.loads((ROOT / name).read_text(encoding="utf-8"))


def variant(value):
    return "".join(part.capitalize() for part in value.split("_"))


def enumeration(name, doc, values):
    lines = [f"/// {doc}", "#[derive(Debug, Clone, Copy, PartialEq, Eq)]", f"pub enum {name} {{"]
    lines += [f"    {variant(value)}," for value in values]
    lines += ["}", "", f"impl {name} {{", "    pub const ALL: &'static [Self] = &[" + ", ".join(f"Self::{variant(v)}" for v in values) + "];",
              "    pub fn as_str(self) -> &'static str {", "        match self {"]
    lines += [f'            Self::{variant(value)} => "{value}",' for value in values]
    lines += ["        }", "    }", "}", ""]
    return lines


def generate():
    metadata, discovery = load("metadata-result.schema.json"), load("discovery-page.schema.json")
    statuses = metadata["$defs"]["status"]["enum"]
    retention = metadata["$defs"]["retention"]["properties"]
    keep = retention["keep"]["enum"]
    reuse_max, offline_max = retention["reuseSeconds"]["maximum"], retention["offlineSeconds"]["maximum"]
    page = discovery["properties"]
    kinds = discovery["$defs"]["item"]["properties"]["kind"]["enum"]
    row = discovery["$defs"]["row"]["properties"]
    out = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by contrib-addons/sdk/schemas/generate-rust.py. Do not edit.",
        "// The schemas are normative; the host also checks every value.",
        "use serde_json::{json, Map, Value};",
        "",
    ]
    out += enumeration("Status", "The status of a metadata result.", statuses)
    out += enumeration("Keep", "Where the host can keep accepted fields.", keep)
    out += enumeration("ItemKind", "The kind of a discovery row.", kinds)
    out += [
        f"pub const MAX_REUSE_SECONDS: u32 = {reuse_max};",
        f"pub const MAX_OFFLINE_SECONDS: u32 = {offline_max};",
        f"pub const MAX_PAGE_ROWS: usize = {page['items']['maxItems']};",
        f"pub const MIN_NEXT_CHECK_SECONDS: u32 = {page['nextCheckSeconds']['minimum']};",
        f"pub const MAX_NEXT_CHECK_SECONDS: u32 = {page['nextCheckSeconds']['maximum']};",
        f"pub const MAX_ITEM_ID: usize = {discovery['$defs']['itemId']['maxLength']};",
        f"pub const MAX_TITLE: usize = {row['title']['maxLength']};",
        f"pub const MAX_MEDIA_KIND: usize = {row['mediaKind']['maxLength']};",
        "",
        "/// The retention record of a metadata result (data.retention).",
        "/// Values above the limits are clamped to them.",
        "#[derive(Debug, Clone, Default, PartialEq, Eq)]",
        "pub struct Retention {",
        "    pub reuse_seconds: Option<u32>,",
        "    pub keep: Option<Keep>,",
        "    pub offline_seconds: Option<u32>,",
        "}",
        "",
        "impl Retention {",
        "    pub fn to_value(&self) -> Value {",
        "        let mut record = Map::new();",
        "        if let Some(seconds) = self.reuse_seconds {",
        '            record.insert("reuseSeconds".into(), json!(seconds.min(MAX_REUSE_SECONDS)));',
        "        }",
        "        if let Some(keep) = self.keep {",
        '            record.insert("keep".into(), json!(keep.as_str()));',
        "        }",
        "        if let Some(seconds) = self.offline_seconds {",
        '            record.insert("offlineSeconds".into(), json!(seconds.min(MAX_OFFLINE_SECONDS)));',
        "        }",
        "        Value::Object(record)",
        "    }",
        "}",
        "",
        "/// A result message: {\"type\":\"result\",\"id\",\"status\",\"data\"}.",
        "pub fn result(id: &str, status: Status, data: Value) -> Value {",
        '    json!({"type": "result", "id": id, "status": status.as_str(), "data": data})',
        "}",
        "",
        "/// One discovery row. Text is cut to the host limits.",
        "#[derive(Debug, Clone, PartialEq)]",
        "pub struct Item {",
        "    pub id: String,",
        "    pub kind: ItemKind,",
        "    pub title: String,",
        "    pub media_kind: Option<String>,",
        "    pub identity: Option<Map<String, Value>>,",
        "    pub available: Option<bool>,",
        "}",
        "",
        "fn cut(text: &str, limit: usize) -> String {",
        "    text.chars().take(limit).collect()",
        "}",
        "",
        "impl Item {",
        "    pub fn new(id: &str, kind: ItemKind, title: &str) -> Self {",
        "        Self { id: id.into(), kind, title: title.into(), media_kind: None, identity: None, available: None }",
        "    }",
        "    /// None when the ID is empty, too long or has a control character.",
        "    pub fn to_value(&self) -> Option<Value> {",
        "        if self.id.is_empty() || self.id.chars().count() > MAX_ITEM_ID || self.id.chars().any(char::is_control) {",
        "            return None;",
        "        }",
        "        let mut row = Map::new();",
        '        row.insert("id".into(), json!(self.id));',
        '        row.insert("kind".into(), json!(self.kind.as_str()));',
        '        row.insert("title".into(), json!(cut(&self.title, MAX_TITLE)));',
        "        if let Some(kind) = &self.media_kind {",
        '            row.insert("mediaKind".into(), json!(cut(kind, MAX_MEDIA_KIND)));',
        "        }",
        "        if let Some(identity) = &self.identity {",
        '            row.insert("identity".into(), Value::Object(identity.clone()));',
        "        }",
        "        if let Some(available) = self.available {",
        '            row.insert("available".into(), json!(available));',
        "        }",
        "        Some(Value::Object(row))",
        "    }",
        "}",
        "",
        "/// The data object of a discovery reply.",
        "#[derive(Debug, Clone, Default, PartialEq)]",
        "pub struct Page {",
        "    pub items: Vec<Item>,",
        "    pub cursor: Option<Value>,",
        "    pub revision: Option<String>,",
        "    pub next_check_seconds: Option<u32>,",
        "    pub removed: Vec<String>,",
        "}",
        "",
        "impl Page {",
        "    /// None when a row is not correct, there are too many rows or the",
        "    /// revision is not 1 to 256 visible ASCII characters.",
        "    pub fn to_value(&self) -> Option<Value> {",
        "        if self.items.len() > MAX_PAGE_ROWS || self.removed.len() > MAX_PAGE_ROWS {",
        "            return None;",
        "        }",
        "        let items = self.items.iter().map(Item::to_value).collect::<Option<Vec<_>>>()?;",
        '        let mut page = Map::new();',
        '        page.insert("items".into(), Value::Array(items));',
        "        if let Some(cursor) = &self.cursor {",
        '            if cursor.as_str() == Some("") {',
        "                return None;",
        "            }",
        '            page.insert("cursor".into(), cursor.clone());',
        "        }",
        "        if let Some(revision) = &self.revision {",
        "            if revision.is_empty() || revision.len() > 256 || !revision.bytes().all(|byte| (0x21..=0x7e).contains(&byte)) {",
        "                return None;",
        "            }",
        '            page.insert("revision".into(), json!(revision));',
        "        }",
        "        if let Some(seconds) = self.next_check_seconds {",
        '            page.insert("nextCheckSeconds".into(), json!(seconds.clamp(MIN_NEXT_CHECK_SECONDS, MAX_NEXT_CHECK_SECONDS)));',
        "        }",
        "        if !self.removed.is_empty() {",
        '            page.insert("removed".into(), json!(self.removed));',
        "        }",
        "        Some(Value::Object(page))",
        "    }",
        "}",
    ]
    return "\n".join(out) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} differs from the schemas. Run generate-rust.py.", file=sys.stderr)
            return 1
        print("contract.rs matches the schemas")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
